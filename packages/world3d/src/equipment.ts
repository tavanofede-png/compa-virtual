import * as T from "three";
import { Model, compact } from "./primitives";
export function equipmentModel(id: string, color = "#6574b0") {
  const m = new Model();
  m.group.name = "equipment:" + id;
  const dark = "#303a51",
    cream = "#f4e9d3",
    gold = "#d9ac53";
  if (id === "headphones") {
    m.torus(0.28, 0.027, dark, [0, 0.02, 0], [0, 0, 0], Math.PI);
    m.torus(0.28, 0.012, color, [0, 0.025, 0.024], [0, 0, 0], Math.PI);
    for (const x of [-0.28, 0.28]) {
      m.box([0.075, 0.16, 0.12], dark, [x, -0.025, 0], 0.04);
      m.box(
        [0.03, 0.125, 0.1],
        color,
        [x + (x > 0 ? 0.045 : -0.045), -0.025, 0],
        0.02,
      );
    }
  } else if (id === "glasses") {
    for (const x of [-0.087, 0.087]) {
      m.torus(0.064, 0.009, dark, [x, 0, 0]).scale.y = 0.8;
      m.rod(
        [x + (x > 0 ? 0.065 : -0.065), 0.008, 0],
        [x + (x > 0 ? 0.1 : -0.1), 0.018, -0.2],
        0.008,
        dark,
      );
    }
    m.tube(
      [
        [-0.025, 0, 0],
        [0, 0.009, 0.012],
        [0.025, 0, 0],
      ],
      0.008,
      dark,
    );
  } else if (id === "scarf") {
    m.torus(0.116, 0.031, "#c97864", [0, 0, 0], [Math.PI / 2, 0, 0]);
    m.box(
      [0.065, 0.22, 0.034],
      "#c97864",
      [-0.052, -0.12, 0.13],
      0.014,
      [0, 0, -0.13],
    );
    for (let i = 0; i < 3; i++)
      m.box(
        [0.012, 0.035, 0.031],
        cream,
        [-0.075 + i * 0.02, -0.244, 0.13],
        0.002,
      );
  } else if (id === "bow") {
    m.ball([0.1, 0.07, 0.032], "#c98391", [-0.09, 0, 0], [0, 0, -0.25]);
    m.ball([0.1, 0.07, 0.032], "#c98391", [0.09, 0, 0], [0, 0, 0.25]);
    m.ball([0.045, 0.046, 0.04], "#aa5e7a");
  } else if (id === "cap") {
    m.mesh(
      new T.SphereGeometry(0.264, 20, 12, 0, Math.PI * 2, 0, Math.PI / 2),
      color,
    );
    m.ball([0.235, 0.016, 0.2], color, [0, 0.005, 0.17]);
    m.ball([0.021, 0.022, 0.021], cream, [0, 0.269, 0]);
  } else if (id === "backpack") {
    m.box([0.4, 0.47, 0.18], color, [0, 0, 0], 0.07);
    m.box([0.29, 0.18, 0.065], dark, [0, -0.095, -0.115], 0.035);
    m.rod([-0.14, 0.05, -0.151], [0.14, 0.05, -0.151], 0.009, gold);
    m.tube(
      [
        [-0.09, 0.235, 0],
        [-0.08, 0.29, 0],
        [0.08, 0.29, 0],
        [0.09, 0.235, 0],
      ],
      0.018,
      dark,
    );
    for (const x of [-0.135, 0.135])
      m.tube(
        [
          [x, 0.19, 0.08],
          [x, 0.15, 0.32],
          [x, -0.22, 0.28],
          [x, -0.23, 0.08],
        ],
        0.025,
        dark,
      );
  } else if (id === "plant") {
    m.cylinder(0.14, 0.105, 0.25, "#d38f72", [0, 0.125, 0]);
    m.cylinder(0.135, 0.135, 0.015, "#634b3b", [0, 0.253, 0]);
    for (let i = 0; i < 7; i++) {
      const a = i * 2.4,
        x = Math.sin(a) * 0.12,
        z = Math.cos(a) * 0.12;
      m.rod([0, 0.24, 0], [x, 0.45 + (i % 3) * 0.05, z], 0.012, "#477d5b");
      m.ball(
        [0.058, 0.135, 0.026],
        i % 2 ? "#6e9970" : "#427c64",
        [x, 0.44 + (i % 3) * 0.05, z],
        [Math.cos(a) * 0.5, a, Math.sin(a) * 0.5],
      );
    }
  } else if (id === "lamp") {
    m.cylinder(0.16, 0.18, 0.035, dark, [0, 0.02, 0]);
    m.rod([0, 0.04, 0], [0, 0.4, 0], 0.021, gold);
    m.cylinder(0.085, 0.18, 0.17, color, [0, 0.47, 0]);
    m.ball([0.05, 0.038, 0.05], "#ffdfa0", [0, 0.405, 0]);
  } else if (id === "globe") {
    m.cylinder(0.17, 0.18, 0.028, gold, [0, 0.015, 0]);
    m.rod([0, 0.025, 0], [0, 0.17, 0], 0.019, dark);
    m.torus(0.25, 0.012, gold, [0, 0.39, 0], [0, 0, 0.3]);
    m.ball([0.21, 0.21, 0.21], "#789fbd", [0, 0.39, 0]);
    for (const [x, y, z, s] of [
      [-0.1, 0.48, 0.145, 0.09],
      [0.09, 0.42, 0.17, 0.07],
      [-0.035, 0.27, 0.15, 0.06],
      [0.12, 0.54, -0.09, 0.07],
    ])
      m.ball([s, s * 0.7, 0.016], "#9db78a", [x, y, z], [0, x * 3, 0]);
  } else if (id === "star-shirt" || id === "overalls") {
    m.box(
      [0.44, 0.52, 0.22],
      id === "overalls" ? "#658a9e" : color,
      [0, 0.32, 0],
      0.07,
    );
    for (const x of [-0.28, 0.28])
      m.box([0.18, 0.22, 0.21], color, [x, 0.49, 0], 0.06, [
        0,
        0,
        x > 0 ? 0.45 : -0.45,
      ]);
    if (id === "overalls")
      for (const x of [-0.12, 0.12])
        m.box([0.055, 0.28, 0.032], cream, [x, 0.55, 0.13], 0.008);
    else m.ball([0.065, 0.065, 0.012], gold, [0, 0.38, 0.13]);
  } else {
    m.box([0.25, 0.25, 0.25], color, [0, 0.125, 0], 0.04);
  }
  return compact(m.group);
}
