import { readdir, mkdir, copyFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
const root = resolve(import.meta.dirname, '..');
const entries = [];
for (const category of ['characters', 'rooms', 'wardrobe', 'pets', 'shared-spaces']) {
  const destination = resolve(root, 'apps/mobile/assets/selection', category);
  await mkdir(destination, { recursive: true });
  for (const name of await readdir(resolve(root, 'apps/web/public/selection', category))) {
    if (!name.endsWith('.webp')) continue;
    await copyFile(resolve(root, 'apps/web/public/selection', category, name), resolve(destination, name));
    entries.push(`  ${JSON.stringify(`${category}/${name.replace('.webp', '')}`)}: require(${JSON.stringify(`../assets/selection/${category}/${name}`)}),`);
  }
}
await writeFile(resolve(root, 'apps/mobile/src/selection-images.ts'), `// Generated by scripts/stage-mobile-selector.mjs. Bundled previews work offline.\nimport type { ImageSourcePropType } from 'react-native';\nexport const selectionImages: Record<string, ImageSourcePropType> = {\n${entries.join('\n')}\n};\n`);
console.log(`Bundled ${entries.length} selector previews.`);
const models = (await readdir(resolve(root, 'apps/web/public/selection/models'))).filter(name => name.endsWith('.glb') && !name.endsWith('-room.glb')).sort();
await writeFile(resolve(root, 'apps/mobile/src/selection-models.ts'), `// Generated from the production models shared with web.\n// Avatars and accessories are bundled; bedrooms use the verified scene cache.\nexport const selectionModels: Record<string, number> = {\n${models.map(name => `  ${JSON.stringify(name)}: require(${JSON.stringify(`../../web/public/selection/models/${name}`)}),`).join('\n')}\n};\n`);
console.log(`Registered ${models.length} shared 3D assets for the native beta.`);
